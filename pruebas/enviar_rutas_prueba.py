CARTAGENA_CENTRO = (10.4236, -75.5513)  # used as the impossible GPS jump


def distancia_m(a, b):
    p1, p2 = radians(a[0]), radians(b[0])
    dp, dl = p2 - p1, radians(b[1] - a[1])
    h = sin(dp / 2) ** 2 + cos(p1) * cos(p2) * sin(dl / 2) ** 2
    return 2 * 6371000 * asin(sqrt(h))


def muestrear(vertices, minutos, semilla, paradas=()):
    """Points every CADA_SEGUNDOS along the path, with a tiny amount of noise (~3 m)
    like a real GPS. `minutos` is the total duration, stops included.
    paradas: [(fraction_of_the_path, minutes_stopped)]. During a stop the vehicle
    does not move but the GPS keeps reporting (the route is NOT cut)."""
    acumulado = [0.0]
    for a, b in zip(vertices, vertices[1:]):
        acumulado.append(acumulado[-1] + distancia_m(a, b))
    total = acumulado[-1]
    ruido = random.Random(semilla)

    def posicion(fraccion):
        d = total * fraccion
        j = 1
        while j < len(acumulado) - 1 and acumulado[j] < d:
            j += 1
        largo = acumulado[j] - acumulado[j - 1] or 1
        f = (d - acumulado[j - 1]) / largo
        lat = vertices[j - 1][0] + (vertices[j][0] - vertices[j - 1][0]) * f
        lon = vertices[j - 1][1] + (vertices[j][1] - vertices[j - 1][1]) * f
        return (round(lat + ruido.uniform(-3e-5, 3e-5), 6),
                round(lon + ruido.uniform(-3e-5, 3e-5), 6))

    lecturas_totales = int(minutos * 60 / CADA_SEGUNDOS)
    pendientes = sorted((f, int(m * 60 / CADA_SEGUNDOS)) for f, m in paradas)
    lecturas_en_marcha = lecturas_totales - sum(n for _, n in pendientes)

    avance = 0.0
    puntos = [posicion(0.0)]
    while len(puntos) < lecturas_totales + 1:
        if pendientes and avance >= pendientes[0][0]:
            _, n = pendientes.pop(0)
            puntos.extend(posicion(avance) for _ in range(n))
            continue
        avance = min(1.0, avance + 1 / lecturas_en_marcha)
        puntos.append(posicion(avance))
    return puntos[:lecturas_totales + 1]


def construir_lecturas():
    """List of (bogota_datetime, lat, lon) in chronological order, plus a
    description of each route for the summary."""
    hoy = datetime.now(BOGOTA).replace(hour=0, minute=0, second=0, microsecond=0)

    def a_las(dias_antes, hora, minuto):
        return hoy - timedelta(days=dias_antes) + timedelta(hours=hora, minutes=minuto)

    lecturas, resumen = [], []

    def agregar(nombre, inicio, puntos):
        for i, (lat, lon) in enumerate(puntos):
            lecturas.append((inicio + timedelta(seconds=CADA_SEGUNDOS * i), lat, lon))
        resumen.append((nombre, inicio, len(puntos)))

    # --- 3 days ago: Barranquilla <-> Santa Marta trip
    agregar("1. Barranquilla -> Santa Marta (112 km, 1 stop)", a_las(3, 6, 30),
            muestrear(TRAZADOS["bq_santamarta"], 105, 11, [(0.5, 10)]))
    agregar("2. Santa Marta: Centro -> Rodadero -> Taganga (2 stops)", a_las(3, 11, 0),
            muestrear(TRAZADOS["sm_local"], 45, 12, [(0.45, 5), (0.8, 10)]))
    agregar("3. Santa Marta -> Barranquilla (110 km, 1 stop)", a_las(3, 16, 30),
            muestrear(TRAZADOS["sm_bq"], 99, 13, [(0.55, 8)]))

    # --- 2 days ago: city trips
    agregar("4. Uninorte -> Centro (Barranquilla)", a_las(2, 8, 0),
            muestrear(TRAZADOS["uninorte_centro"], 17, 1))

    p5 = muestrear(TRAZADOS["centro_buenavista"], 8, 2)
    p5[len(p5) // 2] = CARTAGENA_CENTRO  # impossible GPS jump: the page must discard it
    agregar("5. Centro -> Buenavista (with 1 wrong point)", a_las(2, 17, 0), p5)

    # --- yesterday
    agregar("6. Estadio -> Malecon (Barranquilla)", a_las(1, 7, 30),
            muestrear(TRAZADOS["estadio_malecon"], 16, 3))
    agregar("7. Centro -> Estadio (new route by distance)", a_las(1, 7, 47),
            muestrear(TRAZADOS["centro_estadio"], 12, 4))
