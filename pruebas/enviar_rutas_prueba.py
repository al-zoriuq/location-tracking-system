def mensaje(device, fecha, lat, lon):
    # Same format as UbicacionService.kt, and the one the sniffer expects
    marca = fecha.strftime("%Y-%m-%d %H:%M:%S.") + f"{fecha.microsecond // 1000:03d} -05:00"
    return f"Device: {device}, Lat: {lat}, Lon: {lon}, Timestamp GPS: {marca}"


